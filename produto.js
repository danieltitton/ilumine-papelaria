const productKey = new URLSearchParams(window.location.search).get("produto");
const product = productKey ? products[productKey] : null;
const productDetail = document.querySelector("#product-detail");
const message = document.querySelector("#product-detail-message");

if (!product) {
  message.textContent =
    "Não encontramos esse produto. Volte às categorias para escolher outro.";
  message.hidden = false;
} else {
  const productImage = document.querySelector("#product-image");
  const productImageFrame = document.querySelector(".product-detail-image");
  const galleryImages = product.gallery?.length
    ? product.gallery.map((src, index) => ({
        src,
        alt: `${product.title} — foto ${index + 1}`,
      }))
    : [{ src: product.image, alt: product.imageAlt }];
  productImage.addEventListener("load", () => {
    if (productImage.naturalWidth && productImage.naturalHeight) {
      productImageFrame.style.aspectRatio =
        `${productImage.naturalWidth} / ${productImage.naturalHeight}`;
    }
  });
  const galleryControls = document.querySelector("#product-gallery-controls");
  const galleryThumbnails = document.querySelector(
    "#product-gallery-thumbnails",
  );
  galleryThumbnails.hidden = galleryImages.length <= 1;
  let currentImageIndex = 0;

  document.title = `${product.title} | Ilumine Papelaria`;
  document.querySelector("#product-category").textContent = product.category;
  document.querySelector("#product-title").textContent = product.title;
  document.querySelector("#product-price").textContent = product.price;
  document.querySelector("#product-description").textContent =
    product.description;
  document.querySelector("#product-note").textContent = product.note;

  const showImage = (index) => {
    currentImageIndex =
      (index + galleryImages.length) % galleryImages.length;
    productImage.src = galleryImages[currentImageIndex].src;
    productImage.alt = galleryImages[currentImageIndex].alt;
    document.querySelector("#product-gallery-position").textContent =
      `${currentImageIndex + 1} / ${galleryImages.length}`;
    galleryThumbnails
      .querySelectorAll("button")
      .forEach((thumbnail, thumbnailIndex) => {
        thumbnail.setAttribute(
          "aria-pressed",
          String(thumbnailIndex === currentImageIndex),
        );
      });
  };

  galleryImages.forEach((image, index) => {
    const thumbnail = document.createElement("button");
    thumbnail.className = "product-gallery-thumbnail";
    thumbnail.type = "button";
    thumbnail.setAttribute("aria-label", `Mostrar foto ${index + 1}`);
    thumbnail.setAttribute("aria-pressed", "false");
    const thumbnailImage = document.createElement("img");
    thumbnailImage.src = image.src;
    thumbnailImage.alt = "";
    thumbnailImage.loading = "lazy";
    thumbnail.append(thumbnailImage);
    thumbnail.addEventListener("click", () => showImage(index));
    galleryThumbnails.append(thumbnail);
  });

  if (galleryImages.length > 1) {
    galleryControls.hidden = false;
    document
      .querySelector("#product-gallery-previous")
      .addEventListener("click", () => showImage(currentImageIndex - 1));
    document
      .querySelector("#product-gallery-next")
      .addEventListener("click", () => showImage(currentImageIndex + 1));
  }
  showImage(0);

  const optionsSection = document.querySelector("#product-options-section");
  if (product.options?.length) {
    document.querySelector("#product-options-title").textContent =
      product.optionsTitle;
    const optionsList = document.querySelector("#product-options");
    product.options.forEach((option) => {
      const item = document.createElement("li");
      item.textContent = option;
      optionsList.append(item);
    });
    optionsSection.hidden = false;
  }

  document.querySelector("#product-order").href =
    `https://wa.me/5511958128348?text=${encodeURIComponent(
      `Olá! Tenho interesse em ${product.title}.`,
    )}`;
  productDetail.hidden = false;
}
